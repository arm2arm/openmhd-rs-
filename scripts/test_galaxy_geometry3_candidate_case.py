"""Wrapper metadata controls, each executed on REANA.

All dummy binary/reference bytes below are explicitly incomplete NONPHYSICAL
controls. No positive scientific packet, force, tessellation or error reference
is generated by these tests. The real arithmetic is covered separately.
"""
import copy
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from types import SimpleNamespace
import unittest
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reana/galaxy_geometry3_candidate_case.py'
SPEC = importlib.util.spec_from_file_location('geometry_candidate_job_under_test', SOURCE)
JOB = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(JOB)


def fixture():
    sources = {'supervisor.py': 'tools/m1_evidence/reana_metadata_job.py',
               'launcher.py': 'reana/galaxy_test_case.py',
               'galaxy_geometry3_bridge.py': 'scripts/galaxy_geometry3_bridge.py',
               'compare.py': 'scripts/galaxy_geometry3_compare.py',
               'design.json': 'docs/galaxy/fixtures/geometry3_analytic_v1.json'}
    buffers = {name: (ROOT / path).read_bytes() for name, path in sources.items()}
    selection = dict(name='NONPHYSICAL_METADATA_CONTROL', fixture='bounded_one_cell_2x3x4',
                     scale_index=1, permutation='xyz', translation_index=0)
    literal = dict(schema='openmhd.geometry3.literal-input.v1', case=selection,
                   design_sha256=JOB.PINS['design.json'])
    buffers['input.json'] = JOB.encode(literal)
    buffers['reference.json'] = JOB.encode(dict(schema='openmhd.geometry3.exact-reference.v1',
        case=selection, design_sha256=JOB.PINS['design.json'], input_sha256=JOB.sha(buffers['input.json']),
        candidate_invoked=False, component_accepted=False))
    buffers['runner.py'] = SOURCE.read_bytes()
    buffers['geometry.part0000'] = b'NONPHYSICAL_NOT_AN_EXECUTABLE'
    buffers['root-release.json'] = JOB.encode(dict(schema='openmhd.geometry3-candidate-root-release.v1',
        source_revision='0' * 40, runner_sha256=JOB.sha(buffers['runner.py']),
        binary=JOB.descriptor(buffers['geometry.part0000']), input_sha256=JOB.sha(buffers['input.json']),
        reference_sha256=JOB.sha(buffers['reference.json']),
        prerequisites={name: '0' * 64 for name in JOB.PREREQUISITES}, component_accepted=False))
    buffers['case.json'] = JOB.encode(dict(schema='openmhd.geometry3-candidate-case.v1',
        selection=selection, resources=dict(JOB.RESOURCES),
        root_release_sha256=JOB.sha(buffers['root-release.json'])))
    return buffers


def seal(buffers):
    return JOB.encode(dict(schema='openmhd.geometry3-candidate-inputs.v1',
        files={name: JOB.descriptor(raw) for name, raw in buffers.items()},
        binary=dict(**JOB.descriptor(buffers['geometry.part0000']), parts=['geometry.part0000'])))


class GeometryCandidateCaseMetadataTests(unittest.TestCase):
    def test_metadata_binding_preserves_exact_unexecuted_binary_bytes(self):
        buffers = fixture()
        case, release, binary = JOB.validate_inputs(buffers, seal(buffers))
        self.assertEqual(binary, b'NONPHYSICAL_NOT_AN_EXECUTABLE')
        self.assertEqual(case['root_release_sha256'], JOB.sha(buffers['root-release.json']))
        self.assertIs(release['component_accepted'], False)

    def test_resealed_different_reference_selection_is_rejected(self):
        buffers = fixture()
        reference = JOB.parse(buffers['reference.json'])
        reference['case']['name'] = 'DIFFERENT_NONPHYSICAL_CONTROL'
        buffers['reference.json'] = JOB.encode(reference)
        release = JOB.parse(buffers['root-release.json'])
        release['reference_sha256'] = JOB.sha(buffers['reference.json'])
        buffers['root-release.json'] = JOB.encode(release)
        case = JOB.parse(buffers['case.json'])
        case['root_release_sha256'] = JOB.sha(buffers['root-release.json'])
        buffers['case.json'] = JOB.encode(case)
        with self.assertRaisesRegex(ValueError, 'once-rounded input'):
            JOB.validate_inputs(buffers, seal(buffers))

    def test_binary_part_order_and_changed_bytes_cannot_reach_launch(self):
        buffers = fixture()
        payload = JOB.parse(seal(buffers))
        payload['binary']['parts'] *= 2
        with self.assertRaisesRegex(ValueError, 'Ordered unique'):
            JOB.validate_inputs(buffers, JOB.encode(payload))
        original = seal(buffers)
        buffers['geometry.part0000'] += b'CHANGED'
        with self.assertRaisesRegex(ValueError, 'input digest'):
            JOB.validate_inputs(buffers, original)

    def test_each_external_prerequisite_scope_is_mandatory(self):
        for omitted in JOB.PREREQUISITES:
            buffers = fixture()
            release = JOB.parse(buffers['root-release.json'])
            del release['prerequisites'][omitted]
            buffers['root-release.json'] = JOB.encode(release)
            case = JOB.parse(buffers['case.json'])
            case['root_release_sha256'] = JOB.sha(buffers['root-release.json'])
            buffers['case.json'] = JOB.encode(case)
            with self.subTest(omitted=omitted), self.assertRaisesRegex(ValueError, 'separately scoped'):
                JOB.validate_inputs(buffers, seal(buffers))

    def test_unknown_or_unsettled_command_never_authorizes_comparison(self):
        command = dict(schema='openmhd.metadata-command.v1', outcome='success', returncode=0,
            external_terminal_evidence_required=False, duration_seconds=0.5,
            cleanup=dict(writers_settled=True, direct_child_reaped=True,
                leader_held_until_group_close=True, group_authority_lost=False, remaining_live_pids=[]))
        JOB.successful_command(JOB.parse(JOB.encode(command)))
        for field, value in (('outcome', 'unknown'), ('returncode', False), ('returncode', 1)):
            changed = copy.deepcopy(command)
            changed[field] = value
            with self.subTest(field=field, value=value), self.assertRaisesRegex(ValueError, 'closed child writers'):
                JOB.successful_command(changed)
        changed = copy.deepcopy(command)
        changed['cleanup']['writers_settled'] = None
        with self.assertRaisesRegex(ValueError, 'closed child writers'):
            JOB.successful_command(changed)

    def test_missing_extra_and_unresolved_gates_cannot_pass(self):
        # A helper-only verdict inventory, never a complete geometry packet.
        comparison = dict(schema='openmhd.geometry3.exact-error-comparison.proposal.v1',
            numeric_gates_evaluated=True, execution_provenance_verified=False,
            component_accepted=False, gate_verdicts={name: 'unresolved' for name in JOB.GATES})
        self.assertFalse(JOB.comparison_passed(comparison))
        for gates in ({}, {**comparison['gate_verdicts'], 'unregistered': 'pass'}):
            changed = dict(comparison, gate_verdicts=gates)
            with self.assertRaisesRegex(ValueError, 'Exact eight'):
                JOB.comparison_passed(changed)

    def test_prelaunch_failure_retains_complete_nonpassing_envelope(self):
        with tempfile.TemporaryDirectory() as name:
            work = Path(name)
            (work / 'payload.json').write_bytes(b'{"schema":"wrong","files":{}}')
            with mock.patch.object(JOB, 'load_held') as loader:
                code = JOB.run(work)
            self.assertEqual(code, 1)
            loader.assert_not_called()
            output = work / 'outputs'
            self.assertEqual({p.name for p in output.iterdir()}, set(JOB.OUTPUTS))
            result = JOB.parse((output / 'result.json').read_bytes())
            self.assertEqual(result['status'], 'failed')
            self.assertIs(result['component_accepted'], False)
            self.assertEqual(JOB.parse((output / 'command.json').read_bytes()), {'status': 'not_launched'})

    def test_escaping_native_supervision_retains_unknown_closure_and_raw_logs(self):
        with tempfile.TemporaryDirectory() as name:
            work, buffers = Path(name), fixture()
            for path, raw in buffers.items():
                (work / path).write_bytes(raw)
            (work / 'payload.json').write_bytes(seal(buffers))
            def interrupted(supervisor, argv, cwd, environment, output, timeout, links):
                (output / 'command.json').write_bytes(JOB.encode(dict(status='unknown_closure',
                    outcome='unknown', finished_utc=None, returncode=None,
                    cleanup=dict(writers_settled=None, direct_child_reaped=None))))
                (output / 'stdout.txt').write_bytes(b'ACTUAL_CONTROL_PARTIAL_LOG')
                raise RuntimeError('CONTROL_NATIVE_SUPERVISION_LOSS')
            reducer = SimpleNamespace(compare=mock.Mock(side_effect=AssertionError('Comparison must not run')))
            modules = [SimpleNamespace(runtime_record=lambda *args: {}),
                SimpleNamespace(launch_native=interrupted),
                SimpleNamespace(convert_input=lambda raw: b'NO_GEOMETRY_EVALUATED'), reducer]
            with mock.patch.object(JOB, 'load_held', side_effect=modules):
                code = JOB.run(work)
            self.assertEqual(code, 1)
            reducer.compare.assert_not_called()
            output = work / 'outputs'
            self.assertEqual((output / 'child_raw.bin').read_bytes(), b'ACTUAL_CONTROL_PARTIAL_LOG')
            result = JOB.parse((output / 'result.json').read_bytes())
            command = JOB.parse((output / 'command.json').read_bytes())
            self.assertTrue(result['external_terminal_evidence_required'])
            self.assertEqual(command['status'], 'unknown_closure')
            self.assertIsNone(command['finished_utc'])
            self.assertIsNone(command['returncode'])

    def test_optimized_invocation_stops_before_creating_outputs(self):
        with tempfile.TemporaryDirectory() as name:
            child = subprocess.run([sys.executable, '-B', '-O', str(SOURCE)], cwd=name,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=30)
            self.assertNotEqual(child.returncode, 0)
            self.assertIn(b'Optimized candidate execution rejected', child.stderr)
            self.assertFalse((Path(name) / 'outputs').exists())
