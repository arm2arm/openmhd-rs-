"""Declared-resource/source-link metadata controls; execute only on REANA.

All fixtures are inert synthetic packaging metadata. No Rust command, binary,
network request or numerical result is generated by these controls.
"""
import hashlib
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import prepare_galaxy_reana as packaging


class GalaxySubmissionMetadataTests(unittest.TestCase):
    def synthetic_snapshot(self):
        return {
            'source_revision': 'synthetic-not-an-executed-workflow',
            'upload_sha256': {'source.tar.gz.part000': '1' * 64,
                             'remote.py': '2' * 64,
                             'source.bundle.part000': '3' * 64},
            'source_sha256': {'crates/synthetic/src/lib.rs': '4' * 64},
            'archives': {'source.tar.gz': {'sha256': '5' * 64,
                                         'parts': ['source.tar.gz.part000']}},
        }

    def test_declared_resources_and_fixed_nonexecuting_study(self):
        snapshot = self.synthetic_snapshot()
        value = packaging.specification(snapshot)
        self.assertEqual(value['inputs']['files'],
                         ['snapshot.json', *sorted(snapshot['upload_sha256'])])
        steps = value['workflow']['specification']['steps']
        self.assertEqual(len(steps), 2)
        for step in steps:
            self.assertEqual(step['environment'], packaging.IMAGE)
            self.assertEqual(step['kubernetes_cpu_request'], '4')
            self.assertEqual(step['kubernetes_cpu_limit'], '4')
            self.assertEqual(step['kubernetes_memory_limit'], '8Gi')
        self.assertEqual(steps[0]['commands'], ['python3 remote.py prepare'])
        self.assertEqual(steps[1]['commands'],
                         ['python3 remote.py run --study galaxy-source-preflight --jobs 4'])
        self.assertNotIn('parameters', value['inputs'])
        self.assertIn('outputs/galaxy-preflight/test-binaries.tar.gz', value['outputs']['files'])

    def test_derivation_binds_actual_specification_and_preserves_source_pins(self):
        snapshot = self.synthetic_snapshot()
        original = b'original synthetic workflow metadata; no execution\n'
        original_hash = hashlib.sha256(original).hexdigest()
        snapshot['workflow_sha256'] = original_hash
        with tempfile.TemporaryDirectory() as temporary:
            destination = Path(temporary) / 'synthetic-submission'

            def synthetic_freeze(path, **options):
                self.assertEqual(options, {'minimal': True, 'compact_history': True})
                path.mkdir()
                (path / 'snapshot.json').write_bytes(packaging.encode(snapshot))
                (path / 'reana.yaml').write_bytes(original)

            with patch.object(packaging, 'prepare', side_effect=synthetic_freeze):
                packaging.prepare_source(destination)
            actual = json.loads((destination / 'snapshot.json').read_bytes())
            workflow = (destination / 'reana.yaml').read_bytes()
            self.assertEqual(actual['workflow_sha256'], hashlib.sha256(workflow).hexdigest())
            self.assertEqual(actual['workflow_derivation']['base_workflow_sha256'], original_hash)
            self.assertEqual(actual['workflow_derivation']['test_methods_to_execute'], 0)
            for key in ('source_revision', 'source_sha256', 'upload_sha256', 'archives'):
                self.assertEqual(actual[key], snapshot[key])
            self.assertEqual(json.loads(workflow), packaging.specification(snapshot))

    def test_changed_base_workflow_is_rejected_before_derivation(self):
        snapshot = self.synthetic_snapshot()
        snapshot['workflow_sha256'] = '0' * 64
        changed = b'changed synthetic workflow metadata\n'
        with tempfile.TemporaryDirectory() as temporary:
            destination = Path(temporary) / 'synthetic-submission'

            def synthetic_freeze(path, **_):
                path.mkdir()
                (path / 'snapshot.json').write_bytes(packaging.encode(snapshot))
                (path / 'reana.yaml').write_bytes(changed)

            with patch.object(packaging, 'prepare', side_effect=synthetic_freeze):
                with self.assertRaisesRegex(ValueError, 'Original frozen workflow changed'):
                    packaging.prepare_source(destination)
            self.assertEqual((destination / 'reana.yaml').read_bytes(), changed)
            self.assertNotIn('workflow_derivation', json.loads((destination / 'snapshot.json').read_bytes()))


if __name__ == '__main__':
    unittest.main()
