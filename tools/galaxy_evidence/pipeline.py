PARENT = ('outputs/execution.json', 'outputs/runtime.json', 'outputs/artifacts.sha256.json',
          'outputs/galaxy-preflight/preflight.json', 'outputs/galaxy-preflight/commands.json',
          'outputs/galaxy-preflight/export.json', 'outputs/galaxy-preflight/sha256.json')
TOOLS = ('reana/galaxy_test_case.py', 'tools/m1_evidence/reana_metadata_job.py',
         'tools/m1_evidence/reana_metadata_readonly_adapter.py',
         'tools/galaxy_evidence/readonly_adapter.py', 'tools/galaxy_evidence/common.py',
         'tools/galaxy_evidence/pipeline.py', 'scripts/prepare_galaxy_cases.py')


def tool_capture(files, output):
    for name in TOOLS:
        c.require(c.read(c.ROOT, name) == files[name], 'Execution helper must match original source snapshot')
        c.put(output, 'tools/' + name, files[name])


def tool_fence(files):
    c.require(all(c.read(c.ROOT, name) == files[name] for name in TOOLS), 'Helper source changed during acquisition')


def submission_identity(data, workflow):
    # Accept the existing reana_cases original mapping, or the operational
    # executor's original receipt with an explicit workflow field. No invented
    # acknowledgement is required for a historically uncertain request.
    value = c.parse(data)
    c.require(type(value) is dict and (workflow in value or value.get('workflow') == workflow),
              'Original submission must explicitly identify this workflow')
    return value


def acquire_preflight(source, submission, workflow, output):
    output.mkdir()
    status = dict(schema='openmhd.galaxy-preflight-acquisition.v1', status='preparing',
                  workflow=workflow, component_accepted=False, files={}, started_utc=c.now())
    try:
        snapshot, captured = c.source_capture(source, output)
        original = submission.read_bytes()
        submission_identity(original, workflow)
        c.put(output, 'submission_original.json', original)
        status.update(snapshot_sha256=c.sha(captured['snapshot.json']), submission_sha256=c.sha(original))
        files = c.source_files(output / 'source')
        tool_capture(files, output)
        before, label, identifier = c.attempt(output, 'observe', workflow)
        c.observation(before, workflow, identifier, finished=True)
        status.update(uuid=identifier, before=label)

        def fetch(path):
            raw, receipt, actual = c.attempt(output, 'download', workflow, path)
            c.require(actual == identifier, 'Preflight download UUID changed')
            status['files'][path] = receipt
            return raw

        values = {name: fetch(name) for name in PARENT}
        export = c.parse(values['outputs/galaxy-preflight/export.json'])
        c.require(export['schema'] == 'openmhd.galaxy-rust-preflight-export.v1'
                  and export['snapshot_sha256'] == status['snapshot_sha256']
                  and export['component_accepted'] is False and export['test_methods_executed'] == 0,
                  'Original compile-only export identity')
        blocks = []
        c.require(type(export['parts']) is list and 0 < len(export['parts']) <= 4096, 'Bounded export parts')
        for index, part in enumerate(export['parts']):
            c.require(part['path'] == 'export.part' + str(index).zfill(4), 'Ordered export parts')
            raw = fetch('outputs/galaxy-preflight/' + part['path'])
            c.require(len(raw) == part['bytes'] and 0 < len(raw) <= 1024 * 1024
                      and c.sha(raw) == part['sha256'], 'Actual archive-part identity')
            blocks.append(raw)
        archive = b''.join(blocks)
        c.require(len(archive) == export['archive_bytes'] and c.sha(archive) == export['archive_sha256'],
                  'Exact original exported archive, not regenerated bytes')
        c.extract_export(archive, export['members'], output / 'export')
        c.require(c.read(output / 'export', 'preflight.json') == values['outputs/galaxy-preflight/preflight.json'],
                  'Archive and direct catalog agree')
        commands = c.parse(values['outputs/galaxy-preflight/commands.json'])
        execution = c.parse(values['outputs/execution.json'])
        for row in commands:
            for channel in ('stdout', 'stderr'):
                fetch('outputs/galaxy-preflight/' + row[channel])
        for row in execution['commands']:
            fetch(row['log'])
        after, label, actual = c.attempt(output, 'observe', workflow)
        c.require(actual == identifier and c.observation(before, workflow) ==
                  c.observation(after, workflow, identifier, finished=True), 'Stable preflight observation pair')
        status.update(after=label, status='complete', finished_utc=c.now())
        c.fence(source, captured)
        c.require(submission.read_bytes() == original, 'Original source submission changed')
        tool_fence(files)
        c.write(output, 'acquisition.json', status)
        c.close(output)
        verify_preflight(output)
    except BaseException as error:
        # Never erase partial bodies or a failed/uncertain attempt.
        status.update(status='failed', error_type=type(error).__name__, finished_utc=c.now(),
                      external_terminal_evidence_required=True)
        c.native.persist(output / 'acquisition.json', status)
        if (output / 'files.sha256.json').exists():
            (output / 'files.sha256.json').unlink()
        c.close(output)
        raise


def verify_preflight(root):
    c.verify_closed(root)
    record = c.parse(c.read(root, 'acquisition.json'))
    c.require(record['status'] == 'complete' and record['component_accepted'] is False,
              'Finished immutable parent acquisition')
    snapshot_raw = c.read(root / 'source', 'snapshot.json')
    snapshot = c.parse(snapshot_raw)
    c.require(c.sha(snapshot_raw) == record['snapshot_sha256']
              and c.sha(c.read(root, 'submission_original.json')) == record['submission_sha256'], 'Original source/submission pins')
    submission_identity(c.read(root, 'submission_original.json'), record['workflow'])
    c.require(c.sha(c.read(root / 'source', 'reana.yaml')) == snapshot['workflow_sha256'], 'Original source workflow pin')
    for name, digest in snapshot['upload_sha256'].items():
        c.require(c.sha(c.read(root / 'source', name)) == digest, 'Every original source upload')
    spec = c.parse(c.read(root / 'source', 'reana.yaml'))
    c.require(set(spec['inputs']['files']) == {'snapshot.json', *snapshot['upload_sha256']}
              and len(spec['inputs']['files']) == len(snapshot['upload_sha256']) + 1,
              'Original source workflow upload inventory')
    steps = spec['workflow']['specification']['steps']
    c.require(spec['workflow']['type'] == 'serial' and len(steps) == 2
              and [s['commands'] for s in steps] == [['python3 remote.py prepare'],
                  ['python3 remote.py run --study galaxy-source-preflight --jobs 4']],
              'Original fixed source prerequisite workflow')
    for step in steps:
        c.require(step['environment'] == c.native.IMAGE
                  and all(step[k] == '4' for k in ('kubernetes_cpu_request', 'kubernetes_cpu_limit'))
                  and step['kubernetes_memory_limit'] == '8Gi',
                  'Original declared source-preflight resources/image')
    files = c.source_files(root / 'source')
    tool_fence(files)
    for name in TOOLS:
        c.require(c.read(root, 'tools/' + name) == files[name], 'Captured acquisition implementation source')
    before = c.transport_body(root, record['before'], record['workflow'], record['uuid'], 'observe', None)
    after = c.transport_body(root, record['after'], record['workflow'], record['uuid'], 'observe', None)
    c.require(c.observation(before, record['workflow'], record['uuid'], True) ==
              c.observation(after, record['workflow'], record['uuid'], True), 'Stable original UUID/version')
    values = {name: c.transport_body(root, label, record['workflow'], record['uuid'], 'download', name)
              for name, label in record['files'].items()}
    c.require(set(PARENT) <= set(values), 'All mandatory preflight artifacts downloaded')
    artifacts = c.parse(values['outputs/artifacts.sha256.json'])
    for name, raw in values.items():
        if name != 'outputs/artifacts.sha256.json':
            c.require(artifacts[name] == c.sha(raw), 'Actual server output/manifest linkage')
    report = c.parse(values['outputs/galaxy-preflight/preflight.json'])
    export = c.parse(values['outputs/galaxy-preflight/export.json'])
    c.require(export['preflight_sha256'] == c.sha(values['outputs/galaxy-preflight/preflight.json'])
              and export['snapshot_sha256'] == c.sha(snapshot_raw)
              and export['component_accepted'] is False and type(export['test_methods_executed']) is int
              and export['test_methods_executed'] == 0, 'Compile-only exact export')
    parts = export['parts']
    c.require(0 < len(parts) <= 4096, 'Bounded preflight export')
    archive_parts = []
    for index, part in enumerate(parts):
        c.require(part['path'] == 'export.part' + str(index).zfill(4), 'Ordered transfer parts')
        raw = values['outputs/galaxy-preflight/' + part['path']]
        c.require(c.sha(raw) == part['sha256'] and len(raw) == part['bytes']
                  and 0 < len(raw) <= 1024 * 1024, 'Export transfer digest/size')
        archive_parts.append(raw)
    c.require(c.sha(b''.join(archive_parts)) == export['archive_sha256']
              and sum(map(len, archive_parts)) == export['archive_bytes'], 'Original archive closure')
    expected_members = {'preflight.json': {'sha256': c.sha(values['outputs/galaxy-preflight/preflight.json']),
                                         'bytes': len(values['outputs/galaxy-preflight/preflight.json'])}}
    expected_members.update({v['path']: {'sha256': v['sha256'], 'bytes': v['bytes']} for v in report['binaries']})
    c.require(export['members'] == expected_members, 'Complete catalog/export member agreement')
    c.require(c.inventory(root / 'export') == expected_members, 'Exact extracted regular export')
    for name, item in expected_members.items():
        c.require(artifacts['outputs/galaxy-preflight/' + name] == item['sha256'], 'Export/original output manifest')
    expected_downloads = set(PARENT) | {'outputs/galaxy-preflight/' + p['path'] for p in parts}
    for row in c.parse(values['outputs/galaxy-preflight/commands.json']):
        for channel in ('stdout', 'stderr'):
            path = 'outputs/galaxy-preflight/' + row[channel]
            expected_downloads.add(path)
            c.require(c.sha(values[path]) == row[channel + '_sha256'], 'Actual compile/list raw log')
    for row in c.parse(values['outputs/execution.json'])['commands']:
        expected_downloads.add(row['log'])
        c.require(c.sha(values[row['log']]) == row['log_sha256'], 'Actual prerequisite raw log')
    c.require(set(values) == expected_downloads, 'Exact selected preflight acquisition')
    c.transport_closure(root, [record['before'], *record['files'].values(), record['after']])
    buffers = make_parent_buffers(root, record, files, values, before)
    first = [v for v in report['tests'] if v['manifest'] == 'crates/galaxy-types/Cargo.toml']
    c.require(bool(first), 'Actual identity catalog prerequisite')
    case = dict(schema='openmhd.galaxy-rust-test-case.v1', leaf=first[0],
                resources=dict(threads=1, memory='2Gi', timeout_seconds=180),
                preflight_workflow=record['workflow'], preflight_uuid=record['uuid'],
                input_pins={name: c.sha(raw) for name, raw in buffers.items()})
    c.native.validate_inputs(dict(buffers, **{'case.json': c.encode(case)}), c.supervisor, check_architecture=False)
    tool_fence(files)
    return record, snapshot, files, report, values, before


def make_parent_buffers(root, record, files, values, before):
    observation = c.parse(before)
    # Old supervisor validates the legacy terminal shape; UUID/GET certification
    # remains in the separately pinned acquisition rather than a server label.
    old_observation = dict(schema='openmhd.metadata-server-observation.v1', origin='server',
        observed_utc=observation['observed_utc'],
        matches=[{k: row[k] for k in ('workflow', 'name', 'version', 'status')} for row in observation['matches']])
    buffers = {'case.py': files[c.native.JOB_SOURCE], 'supervisor.py': files[c.native.SUPERVISOR_SOURCE],
               'snapshot.json': c.read(root / 'source', 'snapshot.json'),
               'preflight/server_observation.json': c.encode(old_observation),
               'preflight/acquisition.json': c.read(root, 'acquisition.json')}
    for name in ('preflight.json', 'commands.json'):
        buffers['preflight/' + name] = values['outputs/galaxy-preflight/' + name]
    for name in ('execution.json', 'runtime.json', 'artifacts.sha256.json'):
        buffers['preflight/' + name] = values['outputs/' + name]
    return buffers


def parent_inputs(root):
    record, snapshot, files, report, values, before = verify_preflight(root)
    return record, snapshot, report, make_parent_buffers(root, record, files, values, before)


def specification(names, resources):
    return dict(version='0.9.0', inputs={'files': sorted(names)}, workflow={'type': 'serial', 'specification': {
        'steps': [dict(name='one-native-test', environment=c.native.IMAGE,
                       commands=['python3 -B case.py'], compute_backend='kubernetes',
                       kubernetes_cpu_request='1', kubernetes_cpu_limit='1',
                       kubernetes_memory_limit=resources['memory'])]}},
        outputs={'files': ['outputs/' + n for n in c.native.OUTPUT_NAMES]})


def prepare(parent, coverage, output, prefix):
    c.require(re.fullmatch('[a-z][a-z0-9-]{0,45}', prefix), 'Fresh workflow prefix')
    record, snapshot, report, buffers = parent_inputs(parent)
    contract_raw = coverage.read_bytes()
    contract = c.parse(contract_raw)
    selected = c.catalog(report, contract, snapshot)
    output.mkdir()
    # Preserve the ORIGINAL acquisition closure, sources, observations and GET
    # attempts, not just a reconstructed origin label. No live files are copied.
    shutil.copytree(parent, output / 'context/preflight')
    c.put(output, 'context/coverage.json', contract_raw)
    plan = dict(schema='openmhd.galaxy-native-case-plan.v1', snapshot_sha256=record['snapshot_sha256'],
                parent_manifest_sha256=c.sha(c.read(parent, 'files.sha256.json')),
                coverage_sha256=c.sha(contract_raw), component_accepted=False, cases=[])
    for index, (leaf, resources) in enumerate(selected):
        directory = 'case_' + str(index).zfill(4)
        destination = output / directory
        destination.mkdir()
        case = dict(schema='openmhd.galaxy-rust-test-case.v1', leaf=leaf, resources=resources,
                    preflight_workflow=record['workflow'], preflight_uuid=record['uuid'],
                    input_pins={name: c.sha(raw) for name, raw in buffers.items()})
        inputs = dict(buffers, **{'case.json': c.encode(case)})
        c.native.validate_inputs(inputs, c.supervisor, check_architecture=False)
        binary = c.read(parent / 'export', leaf['binary'])
        c.require(c.sha(binary) == leaf['binary_sha256'], 'Actual exported leaf executable')
        parts = []
        for offset in range(0, len(binary), 1024 * 1024):
            name = 'test-binary.part' + str(len(parts)).zfill(3)
            parts.append(name)
            inputs[name] = binary[offset:offset + 1024 * 1024]
        c.require(0 < len(parts) <= 512, 'Bounded case executable parts')
        for name, raw in inputs.items():
            c.put(destination, name, raw)
        payload = dict(schema='openmhd.galaxy-native-test-inputs.v1',
                       input_sha256={name: c.sha(raw) for name, raw in inputs.items()}, binary_parts=parts)
        c.write(destination, 'payload.json', payload)
        c.write(destination, 'reana.yaml', specification([*inputs, 'payload.json'], resources))
        plan['cases'].append(dict(directory=directory, specification=directory + '/reana.yaml',
            workflow=prefix + '-' + str(index).zfill(4) + '.1', leaf=leaf, resources=resources,
            payload_sha256=c.sha(c.read(destination, 'payload.json')),
            workflow_sha256=c.sha(c.read(destination, 'reana.yaml'))))
    c.require(c.sha(coverage.read_bytes()) == plan['coverage_sha256'], 'Coverage contract changed')
    c.verify_closed(parent)
    c.write(output, 'plan.json', plan)
    return plan


def validate_plan(root):
    plan = c.parse(c.read(root, 'plan.json'))
    c.require(plan['schema'] == 'openmhd.galaxy-native-case-plan.v1' and plan['component_accepted'] is False,
              'Native nonacceptance plan')
    parent = root / 'context/preflight'
    record, snapshot, report, buffers = parent_inputs(parent)
    contract_raw = c.read(root, 'context/coverage.json')
    c.require(plan['parent_manifest_sha256'] == c.sha(c.read(parent, 'files.sha256.json'))
              and plan['snapshot_sha256'] == record['snapshot_sha256']
              and plan['coverage_sha256'] == c.sha(contract_raw), 'Immutable preparation context')
    selected = c.catalog(report, c.parse(contract_raw), snapshot)
    c.require(len(plan['cases']) == len(selected), 'Whole catalog, both profiles')
    seen = set()
    for index, (row, (leaf, resources)) in enumerate(zip(plan['cases'], selected)):
        c.require(row['directory'] == 'case_' + str(index).zfill(4) and row['leaf'] == leaf
                  and row['specification'] == row['directory'] + '/reana.yaml'
                  and row['resources'] == resources and row['workflow'] not in seen
                  and re.fullmatch('[a-z][a-z0-9-]{0,62}\.1', row['workflow']), 'Exact ordered leaf plan')
        seen.add(row['workflow'])
        case_root = root / row['directory']
        payload_raw = c.read(case_root, 'payload.json')
        payload = c.parse(payload_raw)
        c.native.keys(payload, ('schema', 'input_sha256', 'binary_parts'), 'Native payload')
        c.require(payload['schema'] == 'openmhd.galaxy-native-test-inputs.v1', 'Original native payload schema')
        inputs = {name: c.read(case_root, name) for name in payload['input_sha256']}
        c.require(c.sha(payload_raw) == row['payload_sha256']
                  and all(c.sha(raw) == payload['input_sha256'][name] for name, raw in inputs.items()), 'Original planned inputs')
        parts = payload['binary_parts']
        c.require(parts == ['test-binary.part' + str(i).zfill(3) for i in range(len(parts))]
                  and 0 < len(parts) <= 512 and set(inputs) == set(c.native.FIXED_INPUTS) | set(parts)
                  and all(0 < len(inputs[n]) <= 1024 * 1024 for n in parts), 'Exact payload parts/inventory')
        c.require(c.sha(b''.join(inputs[n] for n in parts)) == leaf['binary_sha256'], 'Whole original executable')
        case, actual, _, size = c.native.validate_inputs(inputs, c.supervisor, check_architecture=False)
        c.require(sum(len(inputs[n]) for n in parts) == size, 'Exact exported executable byte count')
        c.require(actual == leaf and case['resources'] == resources
                  and all(inputs[name] == raw for name, raw in buffers.items()), 'Exact prepared parent/leaf')
        spec = c.read(case_root, 'reana.yaml')
        c.require(c.sha(spec) == row['workflow_sha256']
                  and c.parse(spec) == specification([*inputs, 'payload.json'], resources), 'Exact one-leaf workflow/resources')
    return plan, report


def validate_native(values, case_root, report):
    c.require(set(values) == set(c.native.OUTPUT_NAMES), 'Eight actual native artifacts')
    artifacts = c.parse(values['artifacts.sha256.json'])
    c.require(artifacts == {'outputs/' + name: c.sha(raw) for name, raw in values.items()
                           if name != 'artifacts.sha256.json'}, 'Exact native artifact closure')
    result, runtime, command, child = (c.parse(values[n]) for n in
                                      ('result.json', 'runtime.json', 'command.json', 'child_result.json'))
    case_raw, payload_raw = c.read(case_root, 'case.json'), c.read(case_root, 'payload.json')
    case = c.parse(case_raw)
    leaf = case['leaf']
    c.require(result['schema'] == 'openmhd.galaxy-native-test-result.v1' and result['status'] == 'passed'
              and result['component_accepted'] is False and result['case'] == case
              and type(result['test_leaves_executed']) is int and result['test_leaves_executed'] == 1
              and type(result['passing_leaves']) is int and result['passing_leaves'] == 1
              and not result.get('external_terminal_evidence_required', False), 'Actual one-leaf native result')
    for key, expected in (('payload_sha256', c.sha(payload_raw)),
                          ('snapshot_sha256', c.sha(c.read(case_root, 'snapshot.json'))),
                          ('preflight_sha256', c.sha(c.read(case_root, 'preflight/preflight.json'))),
                          ('binary_sha256', leaf['binary_sha256'])):
        c.require(result[key] == expected, 'Result input/source/binary link')
    parent_runtime = c.parse(c.read(case_root, 'preflight/runtime.json'))
    c.require(runtime['kind'] == 'native-rust-libtest' and runtime['image'] == c.native.IMAGE
              and runtime['schema'] == c.supervisor.RUNTIME_SCHEMA
              and runtime['optimized'] == 0 and type(runtime['optimized']) is int
              and runtime['implementation'] == 'CPython' and runtime['machine'] == parent_runtime['machine']
              and runtime['python'] == parent_runtime['python']
              and type(runtime['visible_cpus']) is int and runtime['visible_cpus'] > 0
              and all(runtime[name] is None or type(runtime[name]) is str for name in ('cpu.max', 'memory.max'))
              and runtime['declared_resources'] == case['resources']
              and runtime['thread_environment'] == {name: '1' for name in
                  ('RUST_TEST_THREADS', 'RAYON_NUM_THREADS', 'OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS')},
              'Actual runtime and literal resource/thread declarations')
    cleanup = command['cleanup']
    c.require(command['schema'] == 'openmhd.metadata-command.v1' and command['outcome'] == 'success'
              and type(command['returncode']) is int and command['returncode'] == 0
              and cleanup['writers_settled'] is True and cleanup['direct_child_reaped'] is True
              and cleanup['leader_held_until_group_close'] is True and cleanup['group_authority_lost'] is False
              and cleanup['remaining_live_pids'] == [] and command['external_terminal_evidence_required'] is False,
              'Held leader and actual closed native log writers')
    identity = cleanup['leader_identity']
    c.require(type(command['pid']) is int and command['pid'] > 0
              and command['process_group'] == identity['pid'] == identity['process_group']
              == identity['session'] == command['pid']
              and type(identity['starttime']) is str and re.fullmatch('[0-9]+', identity['starttime']),
              'Actual held private PID/PGID/SID/starttime identity')
    work = Path(command['cwd'])
    c.supervisor.interval(command)
    c.require(c.supervisor.utc(result['finished_utc']) >= c.supervisor.utc(result['started_utc']), 'Native result interval')
    c.require(work.is_absolute() and command['command'] == [str(work / 'test-binary'), '--exact', leaf['selector'],
              '--test-threads', '1', '--color', 'never', '--show-output']
              and command['timeout_seconds'] == case['resources']['timeout_seconds']
              and command['timeout_scope'] == 'direct-child-wait', 'Actual exact native argv/cwd/timeout')
    c.require(runtime['job_path'] == str(work / 'case.py')
              and runtime['child_raw_path'] == str(work / 'outputs/child_raw.bin'), 'Actual runtime paths')
    expected_links = {name: c.sha(raw) for name, raw in (
        ('snapshot', c.read(case_root, 'snapshot.json')), ('case', case_raw), ('payload', payload_raw),
        ('runtime', values['runtime.json']), ('runner', c.read(case_root, 'case.py')),
        ('supervisor', c.read(case_root, 'supervisor.py')))}
    expected_links['binary'] = leaf['binary_sha256']
    c.require(command['links'] == expected_links and values['child_raw.bin'] == values['stdout.txt'],
              'Actual command/source/runtime/binary/raw links')
    binary = [b for b in report['binaries'] if b['path'] == leaf['binary']]
    c.require(all(type(child[n]) is int for n in ('passed', 'failed', 'ignored', 'measured', 'filtered_out'))
              and len(binary) == 1 and child == c.native.witness(values['stdout.txt'], leaf['selector'],
                                                          len(binary[0]['selectors'])), 'Actual named libtest witness')


def collect(cases, submission, output):
    plan, report = validate_plan(cases)
    original = submission.read_bytes()
    state = c.parse(original)
    c.require(type(state) is dict and set(state) == {r['workflow'] for r in plan['cases']}, 'Original whole-catalog submission')
    output.mkdir()
    summary = dict(schema='openmhd.galaxy-native-output-packet.v1', status='collecting',
                   component_accepted=False, physical_accepted=False, cases=[])
    try:
        # Full original immutable input set, including separate original uncertainty.
        captured_inputs = {name: row for name, row in c.inventory(cases).items() if name != 'submission.json'}
        for name, row in captured_inputs.items():
            raw = c.read(cases, name)
            c.require(c.sha(raw) == row['sha256'] and len(raw) == row['bytes'], 'Coherent original prepared file')
            c.put(output / 'inputs', name, raw)
        c.put(output, 'submission_original.json', original)
        original_inputs = c.inventory(output / 'inputs')
        for index, row in enumerate(plan['cases']):
            destination = output / row['directory']
            destination.mkdir()
            record = dict(workflow=row['workflow'], leaf=row['leaf'], directory=row['directory'], status='incomplete', files={})
            summary['cases'].append(record)
            try:
                raw, label, identifier = c.attempt(destination, 'observe', row['workflow'])
                observed = c.observation(raw, row['workflow'], identifier)
                record.update(uuid=identifier, before=label)
                if observed['status'] not in ('finished', 'failed', 'stopped'):
                    record['status'] = 'pending'
                    continue
                values = {}
                for name in c.native.OUTPUT_NAMES:
                    body, receipt, actual = c.attempt(destination, 'download', row['workflow'], 'outputs/' + name)
                    c.require(actual == identifier, 'Original native workflow UUID changed')
                    record['files'][name] = receipt
                    values[name] = body
                after, label, actual = c.attempt(destination, 'observe', row['workflow'])
                record['after'] = label
                c.require(actual == identifier and c.observation(after, row['workflow'], identifier) == observed,
                          'Native observe/download/observe identity')
                c.require(observed['status'] == 'finished', 'Failed/stopped workflow remains forensic/nonpassing')
                validate_native(values, output / 'inputs' / row['directory'], report)
                record['status'] = 'passed'
            except Exception as error:
                record.update(status='failed', error_type=type(error).__name__)
            finally:
                c.native.persist(output / 'summary.json', summary)
        c.require(submission.read_bytes() == original and validate_plan(cases)[0] == plan
                  and c.inventory(output / 'inputs') == original_inputs
                  and {n: r for n, r in c.inventory(cases).items() if n != 'submission.json'} == captured_inputs,
                  'Original input/source generation fence')
        summary.update(status='complete', whole_catalog_passed=all(r['status'] == 'passed' for r in summary['cases']),
                       counts={name: sum(r['status'] == name for r in summary['cases'])
                               for name in ('passed', 'failed', 'pending', 'incomplete')})
    except BaseException as error:
        summary.update(status='failed', error_type=type(error).__name__, whole_catalog_passed=False,
                       external_terminal_evidence_required=True)
        raise
    finally:
        c.native.persist(output / 'summary.json', summary)
        c.close(output)
    verify_results(output)
    return summary


def verify_results(root):
    c.verify_closed(root)
    plan, report = validate_plan(root / 'inputs')
    state = c.parse(c.read(root, 'submission_original.json'))
    c.require(set(state) == {r['workflow'] for r in plan['cases']}, 'Original submission coverage')
    summary = c.parse(c.read(root, 'summary.json'))
    c.require(summary['schema'] == 'openmhd.galaxy-native-output-packet.v1' and summary['status'] == 'complete'
              and summary['component_accepted'] is False and summary['physical_accepted'] is False
              and len(summary['cases']) == len(plan['cases']), 'Complete nonacceptance output packet')
    identifiers = set()
    for row, expected in zip(summary['cases'], plan['cases']):
        c.require(row['workflow'] == expected['workflow'] and row['leaf'] == expected['leaf']
                  and row['directory'] == expected['directory'] and row['uuid'] not in identifiers
                  and row['status'] == 'passed', 'Exact unique catalog/workflow/UUID/pass coverage')
        identifiers.add(row['uuid'])
        directory = root / row['directory']
        before = c.transport_body(directory, row['before'], row['workflow'], row['uuid'], 'observe', None)
        after = c.transport_body(directory, row['after'], row['workflow'], row['uuid'], 'observe', None)
        c.require(c.observation(before, row['workflow'], row['uuid'], True) ==
                  c.observation(after, row['workflow'], row['uuid'], True), 'Actual stable finished native workflow')
        c.require(set(row['files']) == set(c.native.OUTPUT_NAMES), 'Eight raw artifacts per leaf')
        c.transport_closure(directory, [row['before'], *row['files'].values(), row['after']])
        values = {name: c.transport_body(directory, label, row['workflow'], row['uuid'], 'download', 'outputs/' + name)
                  for name, label in row['files'].items()}
        validate_native(values, root / 'inputs' / row['directory'], report)
    c.require(summary['whole_catalog_passed'] is True and all(type(v) is int for v in summary['counts'].values())
              and summary['counts'] ==
              dict(passed=len(plan['cases']), failed=0, pending=0, incomplete=0), 'Actual whole catalog counts')
    return summary


def main(argv=None):
    c.require(__debug__ and sys.flags.optimize == 0, 'Optimized evidence execution rejected')
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='action', required=True)
    acquire = sub.add_parser('acquire-preflight')
    for name in ('source', 'submission', 'output'):
        acquire.add_argument('--' + name, type=Path, required=True)
    acquire.add_argument('--workflow', required=True)
    prepare_parser = sub.add_parser('prepare')
    for name in ('preflight', 'coverage', 'output'):
        prepare_parser.add_argument('--' + name, type=Path, required=True)
    prepare_parser.add_argument('--prefix', required=True)
    collect_parser = sub.add_parser('collect')
    for name in ('cases', 'submission', 'output'):
        collect_parser.add_argument('--' + name, type=Path, required=True)
    verify = sub.add_parser('verify-results')
    verify.add_argument('--packet', type=Path, required=True)
    args = parser.parse_args(argv)
    if args.action == 'acquire-preflight':
        acquire_preflight(args.source.resolve(), args.submission.resolve(), args.workflow, args.output.resolve())
    elif args.action == 'prepare':
        prepare(args.preflight.resolve(), args.coverage.resolve(), args.output.resolve(), args.prefix)
    elif args.action == 'collect':
        collect(args.cases.resolve(), args.submission.resolve(), args.output.resolve())
    else:
        verify_results(args.packet.resolve())


if __name__ == '__main__':
    main()
